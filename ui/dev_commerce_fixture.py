"""Isolated direct-commerce demo; never connects to the real indexer or wallet.

Requires a fresh fixture generated by the Rust fixture example. The discovery
fixture serves only offers/health; browser order traffic goes directly to Rust.
"""
import argparse,json,subprocess,threading
from pathlib import Path
from http.server import BaseHTTPRequestHandler,ThreadingHTTPServer
from server import Handler

class Discovery(BaseHTTPRequestHandler):
    def do_GET(self):
        if self.path not in ('/offers','/healthz'):
            self.send_error(404);return
        data=self.server.offers if self.path=='/offers' else b'ok'
        self.send_response(200);self.send_header('Content-Length',str(len(data)))
        self.send_header('Content-Type','application/json' if self.path=='/offers' else 'text/plain')
        self.end_headers();self.wfile.write(data)
    def log_message(self,*args):pass

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory',type=Path,required=True)
    args=parser.parse_args();directory=args.directory.resolve()
    config=json.loads((directory/'config.json').read_text())
    if config['observer']['mode']!='mock' or config['network']!='testnet' or config['browser_origin']!='http://127.0.0.1:8095':
        raise ValueError('Requires the isolated testnet mock fixture')
    root=Path(__file__).resolve().parent.parent
    seller=subprocess.Popen([str(root/'target/debug/zadp-commerce'),'--config',str(directory/'config.json')],cwd=root)
    discovery=ThreadingHTTPServer(('127.0.0.1',8096),Discovery)
    discovery.offers=(directory/'offers.json').read_bytes()
    ui=ThreadingHTTPServer(('127.0.0.1',8095),Handler);ui.operator=None
    ui.upstream='http://127.0.0.1:8096'
    threading.Thread(target=discovery.serve_forever,daemon=True).start()
    print('LOCAL SIMULATION at http://127.0.0.1:8095 · never send funds to its receiver.',flush=True)
    try:ui.serve_forever()
    finally:
        ui.server_close();discovery.shutdown();discovery.server_close();seller.terminate();seller.wait(timeout=10)
if __name__=='__main__':main()
